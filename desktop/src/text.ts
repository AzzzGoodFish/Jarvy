export const chinese = () => app.getLocale().toLowerCase().startsWith("zh");
export function say(key: keyof Words, values: Record<string, string> = {}): string {
  return (chinese() ? zh : en)[key].replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? "");
}
